# # Техническое задание на лабораторную работу 4
# ## "Система управления данными с веб-интерфейсом"
#
# ### 1. Цель работы
# Разработать веб-приложение для управления данными в таблице с реализацией операций CRUD (Create, Read, Update, Delete) и функциями сортировки.
#
# ### 2. Функциональные требования
#
# #### 2.1. Основной функционал
# - Отображение данных в табличном виде с колонками: ID, Наименование, Категория, Количество, Цена, Статус
# - Добавление записей через модальное окно с валидацией данных
# - Редактирование существующих записей в модальном окне
# - Удаление записей с подтверждением операции
# - Сортировка данных по всем колонкам таблицы (возрастание/убывание)
#
# #### 2.2. Операции с данными (CRUD)
# - Create - добавление новых записей
#   - Поля для ввода: Наименование (обязательное), Категория (выпадающий список), Количество (число), Цена (число), Статус (чекбокс)
#   - Валидация обязательных полей
#   - Автогенерация ID
#
# - Read - отображение всех записей в таблице
#   - Пагинация данных (по 10 записей на странице)
#   - Поиск/фильтрация по наименованию
#
# - Update - редактирование существующих записей
#   - Заполнение формы текущими значениями записи
#   - Сохранение изменений
#
# - Delete - удаление записей
#   - Подтверждение удаления через диалоговое окно
#   - Восстановление удаленных данных (опционально)
#
# #### 2.3. Сортировка и фильтрация
# - Сортировка по клику на заголовок колонки
# - Переключение между возрастающим и убывающим порядком
# - Индикация текущего столбца сортировки
# - Сброс сортировки
#
# ### 3. Технические требования
#
# #### 3.1. Frontend
# - Интерфейс: HTML5, CSS3, JavaScript
# - Фреймворк: Bootstrap 5 для стилизации
# - Таблица: кастомная реализация или DataTables
# - Модальные окна: Bootstrap Modal
# - Валидация форм: нативная HTML5 валидация
#
# #### 3.2. Backend
# - Язык: Python 3.8+
# - Фреймворк: Flask или Django
#
# #### 3.3. API endpoints
# GET    /api/items          - получение всех записей
# POST   /api/items          - создание новой записи
# GET    /api/items/<id>     - получение записи по ID
# PUT    /api/items/<id>     - обновление записи
# DELETE /api/items/<id>     - удаление записи
# GET    /api/items?sort=name&order=asc - сортировка
# ### 4. Интерфейс пользователя
#
# #### 4.1. Основная страница
# - Шапка таблицы с кнопками сортировки
# - Кнопка "Добавить запись" над таблицей
# - Строки таблицы с данными и кнопками действий
# - Пагинация в нижней части таблицы
#
# #### 4.2. Модальное окно редактирования/добавления
# - Поле "Наименование" (текстовый ввод, обязательное)
# - Поле "Категория" (выпадающий список: Электроника, Одежда, Книги, Продукты) - У КАЖДОГО ДОЛЖНО БЫТЬ РАЗНОЕ
# - Поле "Количество"
# - Поле "Цена" (числовой ввод, формат денежный)
# - Поле "Статус" (чекбокс "В наличии")
# - Кнопки "Сохранить" и "Отмена"
#
# #### 4.3. Элементы управления
# - Иконка редактирования (карандаш) в каждой строке
# - Иконка удаления (корзина) в каждой строке
# - Индикатор сортировки (стрелка вверх/вниз) в заголовках
#
# ### 5. Бизнес-логика
#
# #### 5.1. Валидация данных
# - Наименование: не пустое, длина 2-100 символов
# - Категория: из предопределенного списка
# - Количество: целое число ≥ 0
# - Цена: число ≥ 0, два знака после запятой
# - Статус: булево значение
#
# #### 5.2. Обработка ошибок
# - Сообщения об ошибках валидации
# - Подтверждение критических операций (удаление)
# - Уведомления об успешных операциях

